// Render Blog List
export function renderBlogList() {
  const container = document.getElementById('blog-list-container');
  if (container) {
    container.innerHTML = articles.map(a => `
      <a href="#blog/${a.id}" class="blog-item" onclick="openArticle('${a.id}'); return false;">
        <span class="date">${a.date}</span>
        <h4>${a.title}</h4>
        <span class="read-time">${a.readTime}</span>
      </a>
    `).join('');
    
    const countLabel = document.getElementById('blog-count-label');
    if (countLabel) countLabel.textContent = `${articles.length} Artikel`;
  }
}

// Navigation & Reading Router
export function openArticle(id) {
  const article = articles.find(a => a.id === id);
  if (article) {
    const readerDate = document.getElementById('reader-date');
    const readerReadTime = document.getElementById('reader-read-time');
    const readerTitle = document.getElementById('reader-title');
    const readerContent = document.getElementById('reader-content');

    if (readerDate) readerDate.textContent = article.date;
    if (readerReadTime) readerReadTime.textContent = article.readTime;
    if (readerTitle) readerTitle.innerHTML = article.title;
    if (readerContent) readerContent.innerHTML = article.content;
    
    // Hide Hub, Show Reader
    const mainView = document.getElementById('hub-main-view');
    const readerView = document.getElementById('blog-reader-view');
    if (mainView) mainView.style.display = 'none';
    if (readerView) readerView.style.display = 'block';
    
    // Scroll to top smoothly
    window.scrollTo({ top: 0, behavior: 'smooth' });
    
    // Push state to URL
    history.pushState({ articleId: id }, article.title, `#blog/${id}`);
  }
}

export function showHub() {
  const readerView = document.getElementById('blog-reader-view');
  const mainView = document.getElementById('hub-main-view');
  if (readerView) readerView.style.display = 'none';
  if (mainView) mainView.style.display = 'block';
  
  // Clear hash if it was a blog route
  if (window.location.hash.startsWith('#blog/')) {
    history.pushState(null, "Salva — Hub & Blog", window.location.pathname + window.location.search);
  }
}

export function initBlogPage() {
  // Expose click handlers to global window context so inline HTML onclick works
  window.openArticle = openArticle;
  window.showHub = showHub;

  renderBlogList();
  
  // Check initial hash
  const hash = window.location.hash;
  if (hash.startsWith('#blog/')) {
    const id = hash.replace('#blog/', '');
    openArticle(id);
  } else {
    showHub();
  }

  // Handle popstate routing
  window.addEventListener('popstate', (e) => {
    if (e.state && e.state.articleId) {
      openArticle(e.state.articleId);
    } else {
      showHub();
    }
  });
}
